// can't visit
func (c *ConstNode) Accept(Visitor antlr.ParseTreeVisitor) interface{} {
	if v, ok := Visitor.(interface {
		VisitConstNode(v *ConstNode) interface{}
	}); ok {
		return v.VisitConstNode(c)
	}
	return nil
}

func (c *ConstNode) GetText() string {
	switch c.Kind {
	case ConstNodeKindBool:
		return fmt.Sprintf("%t", c.Value.(bool))
	case ConstNodeKindInt:
		return fmt.Sprintf("%d", c.Value.(int))
	case ConstNodeKindFloat:
		return fmt.Sprintf("%f", c.Value.(float64))
	case ConstNodeKindString:
		return fmt.Sprintf("%s", c.Value.(string))
	case ConstNodeKindMap:
		var sb strings.Builder
		sb.WriteString("{")
		for k, v := range c.Value.(map[ConstNode]*ConstNode) {
			sb.WriteString(k.GetText() + ":" + v.GetText())
		}
		sb.WriteString("}")
		return sb.String()
	case ConstNodeKindList:
		var sb strings.Builder
		sb.WriteString("[")
		for i, v := range c.Value.([]ConstNode) {
			sb.WriteString(v.GetText())
			if i < len(c.Value.([]ConstNode)) {
				sb.WriteString(",")
			}
		}
		sb.WriteString("]")
		return sb.String()
	case ConstNodeKindAny:
		return fmt.Sprintf("%v", c.Value)
	default:
		return ""
	}
}

